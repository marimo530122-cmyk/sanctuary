export type RiskLevel = "none" | "ambiguous" | "explicit";

export function extractRisk(rawText: string): { text: string; risk: RiskLevel } {
  const match = rawText.match(/\[\[RISK:(none|ambiguous|explicit)\]\]\s*$/);
  if (!match) return { text: rawText.trim(), risk: "none" };
  const risk = match[1] as RiskLevel;
  const text = rawText.slice(0, match.index).trim();
  return { text, risk };
}
